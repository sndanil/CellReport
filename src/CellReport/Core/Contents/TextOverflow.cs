using System;

namespace CellReport.Core.Contents
{
	/// <summary>
	/// Режим отображения текста, не помещающегося в ячейку.
	/// </summary>
	[Serializable]
	public enum TextOverflow
	{
		/// <summary>
		/// Текущее поведение: перенос по ширине ячейки и обрезка по её границам.
		/// </summary>
		Clip = 0,

		/// <summary>
		/// Одна строка, обрезка с многоточием по ширине ячейки.
		/// </summary>
		Ellipsis = 1,

		/// <summary>
		/// Одна строка; выход в пустые соседние ячейки в сторону выравнивания
		/// (для центрального выравнивания — в обе стороны).
		/// </summary>
		Auto = 2,

		/// <summary>
		/// Одна строка; выход только вправо, в пустые ячейки.
		/// </summary>
		Right = 3,

		/// <summary>
		/// Одна строка; выход только влево, в пустые ячейки.
		/// </summary>
		Left = 4,

		/// <summary>
		/// Одна строка; выход в обе стороны, в пустые ячейки.
		/// </summary>
		Both = 5
	}
}
